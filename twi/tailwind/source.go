package tailwind

import (
	_ "embed"
	"fmt"
	"path/filepath"
	"strconv"
	"strings"

	konst "github.com/pehcastro/twind/internal/konst/style"
	"github.com/pehcastro/twind/twi/style"
)

//go:embed testdata/tailwind-4.3.3/app/output.css
var compilerCorpus string

//go:embed testdata/tailwind-4.3.3/tw-animate-css-1.4.0.css
var twAnimate string

type compileFunc func(string) ([]style.Rule, []Warning, error)

func Input(sources []string) string {
	var b strings.Builder
	b.WriteString("@import \"tailwindcss\" source(none);\n")
	for _, s := range sources {
		b.WriteString("@source " + strconv.Quote(filepath.ToSlash(s)) + ";\n")
	}
	b.WriteString(konst.PresetTheme)
	b.WriteString(twAnimate + "\n")
	return b.String()
}

func Inputs(dir, generated string) ([]string, string, error) {
	return new(Checker).Inputs(dir, generated)
}

func Header(hash string) string {
	return fmt.Sprintf("// %s version=%d hash=%s tailwind=%s\n// Code generated by twirgen. DO NOT EDIT.\n\n", konst.IRMagic, konst.IRVersion, hash, konst.TailwindVersion)
}

func Stale(dir, generated string) (bool, error) {
	return new(Checker).Stale(dir, generated)
}
